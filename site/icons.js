export function iconSvg(name, size = 24) {
  const body = PATHS[name];
  if (body === undefined) {
    throw new Error(`unknown lucide icon: ${name}`);
  }
  return (
    `<svg class="lucide lucide-${name}" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`
  );
}

// Replace every <i data-icon="name"> placeholder with inline SVG so the markup stays readable.
export function mountIcons(root) {
  for (const holder of root.querySelectorAll("i[data-icon]")) {
    const size = Number(holder.dataset.size ?? 20);
    holder.innerHTML = iconSvg(holder.dataset.icon, size);
  }
}
